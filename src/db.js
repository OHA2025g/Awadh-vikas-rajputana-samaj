/** EasyPanel: DATABASE_URL / DB_URL, or DB_HOST + DB_NAME + DB_USER + DB_PASSWORD. */
export function databaseUrl() {
  const url = String(process.env.DATABASE_URL || process.env.DB_URL || '').trim();
  if (url) return url;
  const host = process.env.DB_HOST || process.env.POSTGRES_HOST;
  const name = process.env.DB_NAME || process.env.POSTGRES_DB || process.env.DB_DATABASE;
  if (!host || !name) return '';
  const user = process.env.DB_USER || process.env.POSTGRES_USER || 'postgres';
  const password = process.env.DB_PASSWORD || process.env.POSTGRES_PASSWORD || '';
  const port = process.env.DB_PORT || process.env.POSTGRES_PORT || '5432';
  return `postgres://${encodeURIComponent(user)}:${encodeURIComponent(password)}@${host}:${port}/${name}`;
}

