function translate(sql) {
  return sql
    .replace(/\bINSERT OR IGNORE INTO\b/gi, 'INSERT INTO')
    .replace(/\bMAX\(0,/gi, 'GREATEST(0,')
    .replace(/\sCOLLATE NOCASE\b/gi, '')
    .replace(/\bLIKE\b/gi, 'ILIKE')
    .replace(/ESCAPE\s+'\\'/g, "ESCAPE E'\\\\'")
    .replace(/\bCURRENT_TIMESTAMP\b/g, TS);
}

function bind(sql, args) {
  const first = args[0];
  const named =
    args.length === 1 && first && typeof first === 'object' && !Array.isArray(first) && first.constructor === Object;
  if (named) {
    const names = [];
    const text = sql.replace(/@([a-zA-Z_][a-zA-Z0-9_]*)/g, (_, n) => {
      names.push(n);
      return `$${names.length}`;
    });
    return { text, values: names.map((n) => (first[n] === undefined ? null : first[n])) };
  }
  let i = 0;
  const text = sql.replace(/\?/g, () => `$${++i}`);
  return { text, values: args };
}

function withReturning(sql) {
  if (!/^\s*INSERT\s+INTO\s+/i.test(sql) || /\bRETURNING\b/i.test(sql)) return sql;
  const m = /^\s*INSERT\s+INTO\s+(\w+)/i.exec(sql);
  if (!m || NO_RETURNING.has(m[1].toLowerCase())) return sql;
  return `${sql} RETURNING id`;
}

export const db = {
  prepare(sql) {
    const base = translate(sql);
    return {
      async get(...args) {
        const { text, values } = bind(base, args);
        const { rows } = await client().query(text, values);
        return rows[0];
      },
      async all(...args) {
        const { text, values } = bind(base, args);
        const { rows } = await client().query(text, values);
        return rows;
      },
      async run(...args) {
        const { text, values } = bind(withReturning(base), args);
        const result = await client().query(text, values);
        return { lastInsertRowid: result.rows[0]?.id, changes: result.rowCount };
      },
    };
  },
  async exec(sql) {
    await client().query(sql);
  },
};

export async function tx(fn) {
  if (txClient) return fn();
  const c = await pool.connect();
  txClient = c;
  try {
    await c.query('BEGIN');
    const result = await fn();
    await c.query('COMMIT');
    return result;
  } catch (err) {
    try {
      await c.query('ROLLBACK');
    } catch {
      /* already aborted */
    }
    throw err;
  } finally {
    txClient = null;
    c.release();
  }
}

